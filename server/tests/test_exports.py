"""Excel/PDF exports: content, limits, empty sets, large sets and export audit."""

import hashlib
import io
from datetime import datetime, timedelta

from openpyxl import load_workbook

from app.extensions import db
from app.models import AuditEvent, ExportRecord, Node, TemperatureReading
from tests.conftest import comm_failure, make_node, node_headers, reading

BASE = datetime(2026, 3, 1, 12, 0, 0)
RANGE = {"start": "2026-03-01T00:00", "end": "2026-03-02T00:00"}


def ingest(client, readings):
    for i in range(0, len(readings), 1000):
        r = client.post("/api/v1/readings", json={"readings": readings[i:i + 1000]}, headers=node_headers())
        assert r.status_code == 200 and not r.json["rejected"]


def bulk_rows(n, start=BASE):
    """Insert many readings directly (fast path for large-dataset tests)."""
    node = Node.query.one()
    from app.models import Controller
    ctrl = Controller.query.filter_by(uid="ctrl-1").first() or Controller(node_id=node.id, uid="ctrl-1",
                                                                         poll_interval_s=10)
    db.session.add(ctrl)
    db.session.flush()
    db.session.bulk_insert_mappings(TemperatureReading, [
        {"reading_uid": f"00000000-0000-4000-8000-{i:012d}", "node_id": node.id, "controller_id": ctrl.id,
         "acquired_at": start + timedelta(seconds=10 * i), "received_at": start + timedelta(seconds=10 * i),
         "backfilled": False, "source": "controller", "comm_status": "ok", "quality": "good", "quality_flags": "",
         "temperature_c": -18 + (i % 50) / 10, "setpoint_c": -18.0, "fault_codes": "", "compressor_on": i % 2 == 0,
         "alarm_on": False} for i in range(n)])
    db.session.commit()


def export(client, fmt, data):
    return client.post(f"/logs/export/{fmt}", data=data)


def sample(client):
    make_node()
    ingest(client, [reading(at=BASE, temp=-18.2),
                    reading(at=BASE + timedelta(seconds=10), temp=-17.9, faults=["high_temp"], fault_flags=4),
                    comm_failure(at=BASE + timedelta(seconds=20)),
                    reading(at=BASE + timedelta(minutes=10), temp=-18.5)])  # 10-minute gap before this


def test_excel_export_content(as_user, users, client):
    sample(client)
    r = export(as_user("operator"), "xlsx", {**RANGE, "include_raw": "1"})
    assert r.status_code == 200 and r.headers["Content-Disposition"].startswith("attachment")
    wb = load_workbook(io.BytesIO(r.data))
    assert wb.sheetnames == ["Summary", "Readings", "Gaps", "Fault events"]
    ws = wb["Readings"]
    header = [c.value for c in ws[1]]
    assert header[:5] == ["Timestamp (local)", "Timestamp (UTC)", "Node", "Controller", "Temperature °C"]
    assert header[-1] == "Raw registers"
    rows = list(ws.iter_rows(min_row=2, values_only=True))
    assert len(rows) == 4
    assert rows[0][4] == -18.2 and rows[2][4] is None and rows[2][11] == "timeout"   # chronological, no invented value
    assert isinstance(rows[0][0], datetime)
    assert ws.freeze_panes == "A2"
    summary = [r for r in wb["Summary"].iter_rows(values_only=True) if r and r[0]]
    labels = [r[0] for r in summary]
    assert "Report ID" in labels and "Generated by" in labels and "Records" in labels
    assert list(wb["Gaps"].iter_rows(min_row=2, values_only=True))[0][4].startswith("9m")
    assert list(wb["Fault events"].iter_rows(min_row=2, values_only=True))[0][2] == "high_temp"
    record = ExportRecord.query.one()
    assert record.outcome == "success" and record.record_count == 4 and record.username == "operator"
    assert record.sha256 == hashlib.sha256(r.data).hexdigest()
    assert record.filters["include_raw"] is True and record.filters["start"]
    assert AuditEvent.query.filter_by(action="data_exported").count() == 1


def test_pdf_export(as_user, users, client):
    sample(client)
    r = export(as_user("operator"), "pdf", RANGE)
    assert r.status_code == 200 and r.data.startswith(b"%PDF")
    assert ExportRecord.query.one().record_count == 4


def test_excel_and_pdf_contain_same_record_set(as_user, users, client):
    sample(client)
    c = as_user("operator")
    as_of = "2030-01-01T00:00:00Z"
    export(c, "xlsx", {**RANGE, "as_of": as_of})
    export(c, "pdf", {**RANGE, "as_of": as_of})
    counts = [e.record_count for e in ExportRecord.query.order_by(ExportRecord.id)]
    filters = [e.filters for e in ExportRecord.query.order_by(ExportRecord.id)]
    assert counts == [4, 4]
    assert {k: v for k, v in filters[0].items() if k != "include_raw"} == \
        {k: v for k, v in filters[1].items() if k != "include_raw"}


def test_empty_dataset_exports(as_user, users, client):
    make_node()
    c = as_user("operator")
    x = export(c, "xlsx", RANGE)
    p = export(c, "pdf", RANGE)
    assert x.status_code == 200 and p.status_code == 200 and p.data.startswith(b"%PDF")
    wb = load_workbook(io.BytesIO(x.data))
    assert wb["Readings"].max_row == 1  # header only
    assert [e.record_count for e in ExportRecord.query] == [0, 0]


def test_pdf_limit_refuses_instead_of_truncating(as_user, users, client, app):
    make_node()
    bulk_rows(60)
    app.config["EXPORT_MAX_ROWS_PDF"] = 50
    r = export(as_user("operator"), "pdf", RANGE)
    assert r.status_code == 302
    record = ExportRecord.query.one()
    assert record.outcome == "rejected_too_large" and "Nothing was truncated" in record.error
    assert AuditEvent.query.filter_by(action="data_export_failed").count() == 1


def test_large_excel_export(as_user, users, client):
    make_node()
    bulk_rows(30_000)  # 10 s apart = 83 hours
    r = export(as_user("operator"), "xlsx", {"start": "2026-03-01T00:00", "end": "2026-03-10T00:00"})
    assert r.status_code == 200
    wb = load_workbook(io.BytesIO(r.data), read_only=True)
    assert sum(1 for _ in wb["Readings"].iter_rows(values_only=True)) == 30_001
    assert ExportRecord.query.one().record_count == 30_000


def test_multi_page_pdf_has_page_numbers(as_user, users, client):
    make_node()
    bulk_rows(1500)
    r = export(as_user("operator"), "pdf", RANGE)
    assert r.status_code == 200
    assert r.data.count(b"/Type /Page\n") + r.data.count(b"/Type /Page\r") + r.data.count(b"/Type /Page ") > 5 or \
        r.data.count(b"/Type /Page") > 5


def test_auditor_can_export_viewer_permissions(as_user, users, client):
    sample(client)
    assert export(as_user("auditor"), "xlsx", RANGE).status_code == 200


def test_export_requires_post_with_permission(as_user, users, client):
    sample(client)
    assert as_user("operator").get("/logs/export/xlsx").status_code == 405
